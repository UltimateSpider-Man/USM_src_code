inline constexpr uint32_t MASH_TYPE_COUNT =
    sizeof(MASH_TYPES) / sizeof(MASH_TYPES[0]);

// Sorted by Xbox type; binary search.
inline bool find_pc_mash_type(uint32_t xbox_type, uint32_t &pc_type)
{
    uint32_t lo = 0;
    uint32_t hi = MASH_TYPE_COUNT;
    while (lo < hi) {
        const uint32_t mid = (lo + hi) / 2;
        const uint32_t key = MASH_TYPES[mid].xbox;
        if (key == xbox_type) {
            pc_type = MASH_TYPES[mid].pc;
            return true;
        }
        if (key < xbox_type) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }

    return false;
}

constexpr bool mash_types_sorted()
{
    for (uint32_t i = 1; i < MASH_TYPE_COUNT; ++i) {
        if (MASH_TYPES[i - 1].xbox >= MASH_TYPES[i].xbox) {
            return false;
        }
    }
    return true;
}

static_assert(mash_types_sorted(), "v10 mash type table must be sorted");

